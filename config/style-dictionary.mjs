import StyleDictionary from "style-dictionary";

function extractValues(node) {
  if (node && typeof node === "object") {
    if ("value" in node) return node.value;
    if ("$value" in node) return node.$value;

    const result = {};
    for (const [key, value] of Object.entries(node)) {
      result[key] = extractValues(value);
    }
    return result;
  }
  return node;
}

function walkObject(obj, path, cb) {
  if (obj && typeof obj === "object") {
    for (const [key, value] of Object.entries(obj)) {
      const nextPath = [...path, key];
      if (value && typeof value === "object") {
        if (!Object.values(value).some((v) => v && typeof v === "object")) {
          cb(value, nextPath);
        } else {
          walkObject(value, nextPath, cb);
        }
      } else {
        cb(value, nextPath);
      }
    }
  }
}

/**
 * 1) TS format for tokens.ts
 */
StyleDictionary.registerFormat({
  name: "tailwind/tokens-ts",
  format: ({ dictionary }) => {
    const valuesOnly = extractValues(dictionary.tokens ?? {});

    return [
      "// ⚠️ Auto-generated by Style Dictionary. Do not edit directly.",
      "export const tokens = " +
        JSON.stringify(valuesOnly, null, 2) +
        " as const;",
      "",
      "export type Tokens = typeof tokens;",
      "",
    ].join("\n");
  },
});

/**
 * 2) Generic Tailwind v4 @theme formatter
 *    - spacing / space -> --spacing-*
 *    - color -> --color-*
 *    - radius -> --radius-*
 *    - font.* → base vars + shorthand --font-<role>
 */
StyleDictionary.registerFormat({
  name: "tailwind/theme",
  format: ({ dictionary }) => {
    const lines = [
      "/* ⚠️ Auto-generated by Style Dictionary. Do not edit directly. */",
      "@theme {",
    ];

    // typography accumulators
    const fontFamilies = {};
    const fontSizes = {};
    const fontWeights = {};
    const fontLineHeights = {};

    for (const token of dictionary.allTokens) {
      const path = token.path; // e.g. ["color", "sun"]
      const [root, ...rest] = path;
      const key = rest.join("-"); // e.g. "sun", "bg-page"
      const value = token.value ?? token.$value; // v4 uses value

      if (root === "spacing") {
        // spacing: p-*, m-* etc
        lines.push(`  --spacing-${key}: ${value};`);
      }

      if (root === "color") {
        // colors: bg-*, text-*, etc (depending on naming)
        lines.push(`  --color-${key}: ${value};`);
      }

      if (root === "radius") {
        // border radius
        lines.push(`  --radius-${key}: ${value};`);
      }

      if (root === "typography") {
        const [sub, ...restSub] = rest;
        const role = restSub.join("-"); // "body", "heading", etc.

        if (sub === "family") {
          fontFamilies[role] = value;
          lines.push(`  --font-family-${role}: ${value};`);
        }

        if (sub === "size") {
          fontSizes[role] = value;
          lines.push(`  --font-size-${role}: ${value};`);
        }

        if (sub === "weight") {
          fontWeights[role] = value;
          lines.push(`  --font-weight-${role}: ${value};`);
        }

        if (sub === "lineHeight") {
          fontLineHeights[role] = value;
          lines.push(`  --leading-${role}: ${value};`);
        }
      }
    }

    // Build shorthand font tokens: --font-<role>
    const roles = new Set([
      ...Object.keys(fontSizes),
      ...Object.keys(fontWeights),
      ...Object.keys(fontLineHeights),
    ]);

    const defaultFamilyKey = Object.keys(fontFamilies)[0];
    const defaultFamily =
      defaultFamilyKey == null
        ? "system-ui"
        : `var(--font-family-${defaultFamilyKey})`;

    for (const role of roles) {
      if (!fontSizes[role]) continue; // need a size to build shorthand

      const sizeVar = `var(--font-size-${role})`;
      const weightKey = fontWeights[role] ? role : "body";
      const leadingKey = fontLineHeights[role] ? role : "body";

      const weightVar =
        fontWeights[role] || fontWeights["body"]
          ? `var(--font-weight-${weightKey})`
          : "400";
      const leadingVar =
        fontLineHeights[role] || fontLineHeights["body"]
          ? `var(--leading-${leadingKey})`
          : "1.5";

      const shorthand = `${weightVar} ${sizeVar}/${leadingVar} ${defaultFamily}`;

      lines.push(`  --font-${role}: ${shorthand};`);
    }

    lines.push("}");

    return lines.join("\n");
  },
});

const config = {
  source: ["src/design-tokens/**/*.json"],
  platforms: {
    tailwindTs: {
      transformGroup: "js",
      buildPath: "src/styles/",
      files: [
        {
          destination: "tokens.ts",
          format: "tailwind/tokens-ts",
        },
      ],
    },
    tailwindTheme: {
      transformGroup: "css",
      buildPath: "src/styles/",
      files: [
        {
          destination: "tokens.theme.css",
          format: "tailwind/theme",
        },
      ],
    },
    cssVars: {
      transformGroup: "css",
      buildPath: "src/styles/",
      files: [
        {
          destination: "tokens.css",
          format: "css/variables",
          options: { selector: ":root" },
        },
      ],
    },
  },
};

const sd = new StyleDictionary(config);
await sd.buildAllPlatforms();
